export function useT(): (key: TKey) => string {
  const lang = useApp((s) => s.snapshot?.settings.language ?? 'pt')
  return (key) => dicts[lang][key]
}

export function translate(key: TKey): string {
  const lang = useApp.getState().snapshot?.settings.language ?? 'pt'
  return dicts[lang][key]
}
